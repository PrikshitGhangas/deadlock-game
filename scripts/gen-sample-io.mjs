/**
 * Generates docs/SAMPLE_IO.md from the built-in samples by actually running the engine,
 * so the documented outputs always match the code.   node scripts/gen-sample-io.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SAMPLES } from '../client/src/engine/samples.js';
import { parseSchedule, parseBankers } from '../client/src/engine/parser.js';
import { simulateDetection } from '../client/src/engine/detection.js';
import { simulatePrevention } from '../client/src/engine/prevention.js';
import { simulateBankers } from '../client/src/engine/bankers.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = [];
const p = (s = '') => out.push(s);

p('# Sample inputs and expected outputs');
p('');
p('_Generated by `node scripts/gen-sample-io.mjs` from `client/src/engine/samples.js` — every trace below is the actual engine output._');
p('');

const traceLines = (r) => r.steps.map((s) => `| ${s.index + 1} | ${s.event.replace(/_/g, ' ')} | ${s.op?.text ? `\`${s.op.text}\`` : s.txn || ''} | ${s.explanation.title}${s.cycle && s.event !== 'DEADLOCK_DETECTED' ? '' : ''} |`);

for (const s of SAMPLES) {
  p(`## ${s.title}`);
  p('');
  p(s.description);
  p('');
  p('**Input**');
  p('');
  if (s.input.schedule) {
    p('```');
    p(s.input.schedule);
    p('```');
    if (s.input.victimPolicy) p(`Victim policy: \`${s.input.victimPolicy}\``);
  } else {
    p('```');
    p(`Available : ${s.input.available}`);
    p(`Max       : ${s.input.max.replace(/\n/g, ' | ')}`);
    p(`Allocation: ${s.input.allocation.replace(/\n/g, ' | ')}`);
    if (s.input.request) p(`Request   : P${s.input.request.pid} → ${s.input.request.vector}`);
    p('```');
  }
  p('');
  p('**Expected output**');
  p('');
  p(s.expected.text);
  p('');

  if (s.mode === 'detection') {
    const parsed = parseSchedule(s.input.schedule);
    const r = simulateDetection(parsed.ops, parsed.txns, { victimPolicy: s.input.victimPolicy });
    p(`Summary: ${r.summary.deadlocks} deadlock(s), ${r.summary.rollbacks} rollback(s), ${r.steps.length} steps, committed ${r.summary.committed.join(', ')}${r.summary.stuck.length ? `, stuck ${r.summary.stuck.join(', ')}` : ''}.`);
    p('');
    p('| # | Event | Operation | Explanation |');
    p('|---|---|---|---|');
    traceLines(r).forEach(p);
  } else if (s.mode === 'prevention') {
    const parsed = parseSchedule(s.input.schedule);
    for (const scheme of ['wait-die', 'wound-wait']) {
      const r = simulatePrevention(parsed.ops, parsed.txns, { scheme });
      p(`### ${scheme}`);
      p('');
      p(`Summary: ${r.summary.rollbacks} rollback(s), ${r.steps.length} steps, committed ${r.summary.committed.join(', ')}. Deadlocks: ${r.summary.deadlocks}.`);
      p('');
      p('| # | Event | Operation | Explanation |');
      p('|---|---|---|---|');
      traceLines(r).forEach(p);
      p('');
    }
  } else {
    const r = simulateBankers(parseBankers(s.input));
    p(`Summary: ${r.summary.safe ? `SAFE — sequence ⟨${r.summary.sequence.map((x) => 'P' + x).join(', ')}⟩` : 'UNSAFE'}${r.summary.request ? `; request by P${r.summary.request.pid} ${r.summary.request.granted ? 'GRANTED' : `DENIED (${r.summary.request.reason})`}` : ''}.`);
    p('');
    p('| # | Event | Work | Finish | Explanation |');
    p('|---|---|---|---|---|');
    for (const st of r.steps) {
      p(`| ${st.index + 1} | ${st.event.replace('BANKER_', '')} | ${st.state.work ? `[${st.state.work.join(', ')}]` : `[${st.state.available.join(', ')}]`} | ${st.state.finish ? st.state.finish.map((f) => (f ? 'T' : 'F')).join('') : '—'} | ${st.explanation.title} |`);
    }
  }
  p('');
}

const target = path.join(here, '..', 'docs', 'SAMPLE_IO.md');
fs.writeFileSync(target, out.join('\n'));
console.log(`wrote ${target} (${out.length} lines)`);
